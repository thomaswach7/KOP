export const LANGUAGES = ['de', 'en'];

/** Liefert t(key, vars). Unbekannte Sprache → Englisch, unbekannter Schlüssel → der Schlüssel selbst. */
export function createI18n(lang) {
  const table = STRINGS[lang] ?? STRINGS.en;
  return (key, vars) => {
    const text = table[key] ?? STRINGS.en[key] ?? key;
    return vars ? text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m)) : text;
  };
}

/** Sprache aus den Browser-Einstellungen: Deutsch für de-*, sonst Englisch. */
export function detectLanguage(preferred) {
  for (const tag of preferred ?? []) {
    const short = String(tag).toLowerCase().slice(0, 2);
    if (LANGUAGES.includes(short)) return short;
  }
  return 'en';
}
